#[repr(C)]
#[derive(Copy, Clone, bytemuck::Pod, bytemuck::Zeroable)]
pub struct UiVertex {
    pub pos: [f32; 2],
    pub color: [f32; 4],
}

pub fn build_text_quads(
    lines: &[String],
    start_px: (f32, f32),
    surface_px: (f32, f32),
    out: &mut Vec<UiVertex>,
    color: [f32; 4],
    cell: f32,
) {
    let (sx, sy) = start_px;
    let (sw, sh) = surface_px;
    let glyph_w = 5.0 * cell;
    let glyph_h = 7.0 * cell;
    let line_gap = cell * 2.0;
    for (li, line) in lines.iter().enumerate() {
        let y_line = sy + li as f32 * (glyph_h + line_gap);
        let mut x_cursor = sx;
        for ch in line.chars() {
            let rows = glyph5x7_rows(ch);
            for (ry, row) in rows.iter().enumerate() {
                for cx in 0..5 {
                    if (row >> (4 - cx)) & 1 == 1 {
                        let px0 = x_cursor + cx as f32 * cell;
                        let py0 = y_line + ry as f32 * cell;
                        let px1 = px0 + cell;
                        let py1 = py0 + cell;
                        let x0 = -1.0 + px0 * 2.0 / sw;
                        let y0 = 1.0 - py0 * 2.0 / sh;
                        let x1 = -1.0 + px1 * 2.0 / sw;
                        let y1 = 1.0 - py1 * 2.0 / sh;
                        out.extend_from_slice(&[
                            UiVertex {
                                pos: [x0, y0],
                                color,
                            },
                            UiVertex {
                                pos: [x1, y0],
                                color,
                            },
                            UiVertex {
                                pos: [x0, y1],
                                color,
                            },
                            UiVertex {
                                pos: [x0, y1],
                                color,
                            },
                            UiVertex {
                                pos: [x1, y0],
                                color,
                            },
                            UiVertex {
                                pos: [x1, y1],
                                color,
                            },
                        ]);
                    }
                }
            }
            x_cursor += glyph_w + cell;
        }
    }
}
